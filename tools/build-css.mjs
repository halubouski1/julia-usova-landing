// Bundle and minify all stylesheets into css/site.min.css (the only CSS the
// page loads, so the first paint waits for one request instead of five).
//
//   npm run build:css        (run after every change to a CSS source)
//
// Sources stay the files you edit, in cascade order:
// normalize → vendor (lenis, aos) → style.css → media.css.
// `npm run build:css` regenerates the laptop block (tools/scale-laptop.py) first.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { transform } from 'lightningcss';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = [
  'css/normalize.css',
  'css/vendor/lenis-1.1.13.css',
  'css/vendor/aos-2.3.4.css',
  'css/style.css',
  'css/media.css',
];
const OUTPUT = 'css/site.min.css';

const input = SOURCES.map((file) => readFileSync(path.join(ROOT, file), 'utf8')).join('\n');

// Targets = the oldest browsers the site already needs (color-mix, individual
// transforms). Without targets lightningcss drops -webkit-backdrop-filter,
// which Safari < 18 requires. With them it keeps the prefixes and does not
// rewrite any modern syntax the CSS uses.
const v = (major, minor = 0) => (major << 16) | (minor << 8);
const targets = { safari: v(16, 4), ios_saf: v(16, 4), chrome: v(111), firefox: v(113), edge: v(111) };

const { code, warnings } = transform({
  filename: OUTPUT,
  code: Buffer.from(input),
  minify: true,
  targets,
  errorRecovery: false,
});
for (const w of warnings) console.warn('warning:', w.message);

const banner = `/* Generated by tools/build-css.mjs from ${SOURCES.join(', ')}. Do not edit. */\n`;
writeFileSync(path.join(ROOT, OUTPUT), banner + code);

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log(`${SOURCES.length} files, ${kb(input.length)} → ${OUTPUT} ${kb(code.length + banner.length)}`);
