#!/usr/bin/env python3
"""Regenerate the laptop (1280–1919px) block of css/media.css from css/style.css.

Every declaration in style.css that contains px values is copied with those
values multiplied by 0.75. 1px values (hairlines, borders) are kept as is.
@font-face, @keyframes and @media blocks of style.css are skipped.

The output replaces everything between the markers
    /* laptop:generated:start */ … /* laptop:generated:end */
in css/media.css. Hand-written laptop overrides go after the end marker.

Run from the project root:  python3 tools/scale-laptop.py
"""
import re
from pathlib import Path

SCALE = 0.75
ROOT = Path(__file__).resolve().parent.parent
STYLE = ROOT / 'css' / 'style.css'
MEDIA = ROOT / 'css' / 'media.css'
START = '/* laptop:generated:start */'
END = '/* laptop:generated:end */'

# Selectors of components shared by all pages go first (CLAUDE.md order rule)
SHARED_PREFIXES = (':root', '.container', '.label', '.btn', '.header', '.nav', '.burger',
                   '.footer', '.booking-form', '.field', '.to-top', ':focus')

PX = re.compile(r'(-?\d*\.?\d+)px')


def scale_value(value):
    def repl(match):
        number = float(match.group(1))
        if abs(number) == 1:
            return match.group(0)
        scaled = round(number * SCALE, 3)
        text = ('%.3f' % scaled).rstrip('0').rstrip('.')
        return (text if text not in ('-0', '') else '0') + 'px'
    return PX.sub(repl, value)


def split_declarations(body):
    """Split on ';' outside quotes and parentheses (data URIs contain ';')."""
    parts, buf, depth, quote = [], '', 0, None
    for ch in body:
        if quote:
            buf += ch
            if ch == quote:
                quote = None
            continue
        if ch in '"\'':
            quote = ch
        elif ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        elif ch == ';' and depth == 0:
            parts.append(buf)
            buf = ''
            continue
        buf += ch
    if buf.strip():
        parts.append(buf)
    return [p.strip() for p in parts if p.strip()]


def top_level_rules(css):
    """Yield (selector, body) for top-level rules; skip at-rule blocks."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        brace = css.find('{', i)
        if brace == -1:
            break
        selector = css[i:brace].strip()
        depth, j = 1, brace + 1
        while j < n and depth:
            if css[j] == '{':
                depth += 1
            elif css[j] == '}':
                depth -= 1
            j += 1
        body = css[brace + 1:j - 1]
        i = j
        if selector.startswith('@'):
            continue
        yield selector, body


def build():
    shared, page = [], []
    for selector, body in top_level_rules(STYLE.read_text()):
        decls = [d for d in split_declarations(body) if PX.search(d.split(':', 1)[-1])]
        decls = [d.split(':', 1)[0].strip() + ': ' + scale_value(d.split(':', 1)[1].strip()) for d in decls]
        if not decls:
            continue
        sel = ' '.join(selector.split())
        block = '  %s {\n%s\n  }' % (sel.replace(', ', ',\n  '), '\n'.join('    %s;' % d for d in decls))
        (shared if sel.startswith(SHARED_PREFIXES) else page).append(block)
    return ('  ' + START + '\n'
            '  /* Generated by tools/scale-laptop.py from style.css (px × 0.75). Do not edit by hand. */\n\n'
            '  /* Shared */\n' + '\n\n'.join(shared) + '\n\n'
            '  /* index.html */\n' + '\n\n'.join(page) + '\n  ' + END)


def main():
    media = MEDIA.read_text()
    start, end = media.find('  ' + START), media.find(END)
    if start == -1 or end == -1:
        raise SystemExit('markers not found in css/media.css')
    media = media[:start] + build() + media[end + len(END):]
    MEDIA.write_text(media)
    print('laptop block regenerated')


if __name__ == '__main__':
    main()
