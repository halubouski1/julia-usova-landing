// Bundle the page scripts into js/site.min.js (one request instead of three).
//
//   npm run build:js         (run after every change to js/main.js)
//
// Order = execution order the page relies on: Lenis and AOS define their
// globals, then main.js uses them. Vendor files are already minified and are
// copied as-is; only main.js is minified (esbuild, ES2020, same semantics).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { transformSync } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = ['js/vendor/lenis-1.1.13.min.js', 'js/vendor/aos-2.3.4.js'];
const MAIN = 'js/main.js';
const OUTPUT = 'js/site.min.js';

const read = (file) => readFileSync(path.join(ROOT, file), 'utf8');
const main = transformSync(read(MAIN), { minify: true, target: 'es2020', legalComments: 'none' }).code;

const parts = [...VENDOR.map(read), main];
const banner = `/* Generated by tools/build-js.mjs from ${[...VENDOR, MAIN].join(', ')}. Do not edit. */\n`;
// `;` between files: each one is a self-contained IIFE/UMD script
const code = banner + parts.map((p) => p.trim().replace(/;?$/, ';')).join('\n') + '\n';
writeFileSync(path.join(ROOT, OUTPUT), code);

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
const before = [...VENDOR, MAIN].reduce((sum, f) => sum + read(f).length, 0);
console.log(`${VENDOR.length + 1} files, ${kb(before)} → ${OUTPUT} ${kb(code.length)}`);
