// Builds js/vendor/swiper-<version>.custom.min.js and copies the core CSS to
// css/vendor/ (`npm run build:swiper`). Only needed when the Swiper version or
// the list of modules in tools/vendor-src/swiper-entry.mjs changes; the output
// is committed like the other vendor files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildSync } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(path.join(ROOT, 'node_modules/swiper/package.json'), 'utf8'));
const js = `js/vendor/swiper-${version}.custom.min.js`;
const css = `css/vendor/swiper-${version}.min.css`;

const result = buildSync({
  entryPoints: [path.join(ROOT, 'tools/vendor-src/swiper-entry.mjs')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  legalComments: 'none',
  write: false,
});
const banner = `/* Swiper ${version} (MIT, https://swiperjs.com) — core + Navigation, Keyboard, A11y.\n   Generated by tools/build-swiper.mjs from tools/vendor-src/swiper-entry.mjs. Do not edit. */\n`;
writeFileSync(path.join(ROOT, js), banner + result.outputFiles[0].text);
writeFileSync(path.join(ROOT, css), readFileSync(path.join(ROOT, 'node_modules/swiper/swiper.min.css'), 'utf8'));
console.log(`${js} ${(result.outputFiles[0].text.length / 1024).toFixed(1)} KB, ${css}`);
